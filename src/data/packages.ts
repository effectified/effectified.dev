// The facades of effectified/packages, as the site lists them: each one's docs.json and SKILL.md, which the engine
// generates into every facade, read from a checkout of effectified/packages, with its library's npm downloads. Read
// at build time, so a site build shows what is released now: nothing here names a version by hand.

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";

/** docs.json, schema 2, as `src/docs.ts` of effectified/engine writes it; the site reads the fields it shows. */
export interface FacadeDocs {
	readonly schema: 2;
	readonly name: string;
	readonly slug: string;
	readonly kind: "runtime" | "ui";
	readonly tagline?: string;
	readonly description: string;
	readonly upstream: { readonly package: string; readonly version: string; readonly npm: string };
	readonly version: string;
	readonly engine: string;
	readonly page: string;
	readonly source: string;
	/**
	 * The package installs by `name` from npm (`npm`, its page there), with Effect UI's snapshot build beside it for a
	 * frontend facade (`effectUi`, a URL); `tag` is its GitHub release, which holds its notes and demo.
	 */
	readonly install: { readonly npm: string; readonly tag: string; readonly effectUi?: string };
	readonly demo?: { readonly url: string; readonly pages: ReadonlyArray<string> };
	readonly tests: number;
	readonly examples: ReadonlyArray<{ readonly title: string; readonly source: string; readonly code: string; readonly demo?: string }>;
	readonly api: {
		readonly exports: ReadonlyArray<string>;
		readonly services: ReadonlyArray<{ readonly name: string; readonly handle: string; readonly acquire: string }>;
		readonly errors: ReadonlyArray<{ readonly tag: string; readonly instanceOf?: string; readonly codes: ReadonlyArray<string> }>;
		readonly handles: ReadonlyArray<{
			readonly name: string;
			readonly release?: string;
			readonly effects: ReadonlyArray<string>;
			readonly streams: ReadonlyArray<string>;
			readonly sync: ReadonlyArray<string>;
			readonly events: ReadonlyArray<string>;
		}>;
		readonly elements: ReadonlyArray<{
			readonly tag: string;
			readonly name: string;
			readonly description: string;
			readonly properties: ReadonlyArray<string>;
			readonly events: ReadonlyArray<string>;
			readonly changes: ReadonlyArray<string>;
		}>;
		readonly mounts: ReadonlyArray<string>;
	};
}

/** A facade as the site shows it: its docs, its skill, and its library's downloads last week when npm answered. */
export interface Facade extends FacadeDocs {
	readonly skill: string;
	readonly weekly?: number;
}

const REPOSITORY = "https://github.com/effectified/packages";

/**
 * Where effectified/packages is checked out: `EFFECTIFIED_PACKAGES` (CI checks it out), a sibling checkout
 * (`../packages`, for working on both), or a shallow clone kept under node_modules/.cache.
 */
export function packagesCheckout(): string {
	const configured = process.env["EFFECTIFIED_PACKAGES"];
	if (configured !== undefined && configured !== "") return resolve(configured);
	const sibling = resolve("../packages");
	if (existsSync(join(sibling, "targets"))) return sibling;
	const cache = resolve("node_modules/.cache/effectified-packages");
	if (existsSync(join(cache, ".git"))) execFileSync("git", ["-C", cache, "pull", "--ff-only", "--quiet"]);
	else execFileSync("git", ["clone", "--depth", "1", "--quiet", REPOSITORY, cache]);
	return cache;
}

/** Every facade's docs and skill, read from the checkout; a facade whose docs.json is another schema is left out, with a warning. */
export function readFacadeDocs(): ReadonlyArray<FacadeDocs & { readonly skill: string }> {
	const targets = join(packagesCheckout(), "targets");
	return readdirSync(targets)
		.sort()
		.flatMap((target) => {
			const directory = join(targets, target, "package");
			if (!existsSync(join(directory, "docs.json"))) return [];
			// docs.json is generated by the engine and committed: a stored format, checked by its schema number.
			const docs = JSON.parse(readFileSync(join(directory, "docs.json"), "utf8")) as { readonly schema?: unknown };
			if (docs.schema !== 2) {
				console.warn(`effectified: ${target} left out, its docs.json is schema ${String(docs.schema)}, the site reads 2`);
				return [];
			}
			return [{ ...(docs as FacadeDocs), skill: readFileSync(join(directory, "SKILL.md"), "utf8") }];
		});
}

/** The facades with their libraries' downloads last week, most downloaded first. */
export async function readFacades(): Promise<ReadonlyArray<Facade>> {
	const facades = await Promise.all(
		readFacadeDocs().map(async (docs): Promise<Facade> => {
			const weekly = await weeklyDownloads(docs.upstream.package);
			return weekly === undefined ? docs : { ...docs, weekly };
		}),
	);
	return facades.sort((a, b) => (b.weekly ?? 0) - (a.weekly ?? 0) || a.slug.localeCompare(b.slug));
}

/** A package's downloads last week from npm's API; undefined when it does not answer (a build offline, say). */
async function weeklyDownloads(name: string): Promise<number | undefined> {
	try {
		const response = await fetch(`https://api.npmjs.org/downloads/point/last-week/${name}`);
		if (!response.ok) return undefined;
		const body = (await response.json()) as { readonly downloads?: unknown };
		return typeof body.downloads === "number" ? body.downloads : undefined;
	} catch {
		return undefined;
	}
}
